/* ==================== 轻量字符串辅助 ==================== */

static bool str_eq(const char* a, const char* b)
{
    if (!a || !b) return false;
    while (*a && *a == *b) { a++; b++; }
    return (*a == *b);
}

static void str_cpy(char* dst, const char* src)
{
    if (!dst) return;
    if (!src) { *dst = 0; return; }
    while (*src) *dst++ = *src++;
    *dst = 0;
}

/* 子串匹配（不区分大小写） */
static bool str_contains(const char* hay, const char* needle)
{
    if (!hay || !needle) return false;
    for (int i = 0; hay[i]; i++)
    {
        int j = 0;
        while (hay[i + j] && needle[j] && hay[i + j] == needle[j]) j++;
        if (!needle[j]) return true;
    }
    return false;
}

/* 从耗材名称关键词识别材质（第三方耗材 filament_id 常不规范，靠名称兜底） */
static const char* material_from_name(const char* nm)
{
    if (!nm) return NULL;

    char up[20];
    int ul = 0;
    for (int i = 0; nm[i] && ul < 19; i++)
    {
        char c = nm[i];
        if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
        up[ul++] = c;
    }
    up[ul] = 0;

    if (str_contains(up, "PETG")) return "PETG";
    if (str_contains(up, "PCTG")) return "PCTG";
    if (str_contains(up, "PLA"))  return "PLA";
    if (str_contains(up, "ABS"))  return "ABS";
    if (str_contains(up, "ASA"))  return "ASA";
    if (str_contains(up, "NYLON")) return "PA";
    if (str_contains(up, "PC"))   return "PC";
    if (str_contains(up, "PA"))   return "PA";
    if (str_contains(up, "TPU"))  return "TPU";
    return NULL;
}

/* ==================== 硬件 I2C2 底层 ==================== */

/**
 * @brief OLED I2C 写命令（单字节）
 *
 * I2C 时序：START → 0x78(addr+W) → 0x00(命令模式) → cmd → STOP
 * 使用硬件 I2C2，比软件 bit-bang 更快更稳定
 */
void SSD1306_OLED::write_cmd(uint8_t c)
{
    if (!s_ready) return;
    uint8_t buf[2] = { 0x00u, c };
    if (i2c2_write(BMCU_OLED_ADDR, buf, 2))
        s_ready = false;   // I2C 写失败（NACK/超时）→ 标记 OLED 不在线，后续全部跳过
}

/**
 * @brief OLED I2C 写数据（单字节）
 *
 * I2C 时序：START → 0x78(addr+W) → 0x40(数据模式) → data → STOP
 */
void SSD1306_OLED::write_data(uint8_t d)
{
    if (!s_ready) return;
    uint8_t buf[2] = { 0x40u, d };
    if (i2c2_write(BMCU_OLED_ADDR, buf, 2))
        s_ready = false;
}

/**
 * @brief OLED I2C 连续写数据（多字节，单次事务）
 *
 * SSD1306 支持连续写：一次 START + 地址 + 控制字节(0x40) 后，
 * 可连续发任意多个数据字节，最后 STOP。比逐字节事务效率高得多。
 * 硬件 I2C2 下一次事务可发最多 128+1=129 字节（清一整页）。
 */
static void oled_write_data_bulk(const uint8_t* data, uint8_t n)
{
    if (!SSD1306_OLED::is_ready() || n == 0) return;
    uint8_t buf[129];
    buf[0] = 0x40u;
    for (uint8_t i = 0; i < n; i++)
        buf[i + 1u] = data[i];
    if (i2c2_write(BMCU_OLED_ADDR, buf, (uint32_t)(n + 1u)))
        SSD1306_OLED::set_not_ready();
}

/* ==================== 探测 OLED ACK ==================== */

/**
 * @brief 探测 OLED 是否在线（ACK 检测）
 *
 * 仅发送 I2C 地址字节，检查从机是否 ACK。
 * 不修改 s_ready，仅返回探测结果。用于运行时热插拔检测。
 *
 * CH32V203 硬件 I2C 的 AF（Acknowledge Failure）标志位在从机 NACK 时置位，
 * 读取后自动清除。通过检查此标志位判断设备是否应答。
 */
bool SSD1306_OLED::probe_ack()
{
    /* 先清除残留的 AF 标志和总线状态，避免上次事务遗留误判 */
    I2C_ClearFlag(I2C2, I2C_FLAG_AF);
    I2C_ClearFlag(I2C2, I2C_FLAG_BERR);

    /* 等待总线空闲；若 SDA 被拉低（总线挂死），做一次总线复位 */
    uint32_t t0 = time_ms64();
    while (I2C_GetFlagStatus(I2C2, I2C_FLAG_BUSY))
    {
        if ((time_ms64() - t0) > 50u)
        {
            /* 总线挂死：软件复位 I2C2 外设 */
            I2C_Cmd(I2C2, DISABLE);
            I2C_SoftwareResetCmd(I2C2, ENABLE);
            I2C_SoftwareResetCmd(I2C2, DISABLE);
            I2C_Cmd(I2C2, ENABLE);
            delay(1);
            /* 复位后再清 AF */
            I2C_ClearFlag(I2C2, I2C_FLAG_AF);
            return false;
        }
    }

    /* 发送 START */
    I2C_GenerateSTART(I2C2, ENABLE);
    t0 = time_ms64();
    while (!I2C_CheckEvent(I2C2, I2C_EVENT_MASTER_MODE_SELECT))
    {
        if ((time_ms64() - t0) > 50u) { I2C_GenerateSTOP(I2C2, ENABLE); return false; }
    }

    /* 发送从机地址 + 写位 */
    I2C_Send7bitAddress(I2C2, (uint8_t)(BMCU_OLED_ADDR << 1u), I2C_Direction_Transmitter);
    t0 = time_ms64();
    while (!I2C_CheckEvent(I2C2, I2C_EVENT_MASTER_TRANSMITTER_MODE_SELECTED))
    {
        if ((time_ms64() - t0) > 50u) { I2C_GenerateSTOP(I2C2, ENABLE); return false; }
    }

    /* 检查 AF 标志：从机 NACK 时置位 */
    bool ack = !I2C_GetFlagStatus(I2C2, I2C_FLAG_AF);
    I2C_GenerateSTOP(I2C2, ENABLE);
    I2C_ClearFlag(I2C2, I2C_FLAG_AF);
    return ack;
}

/* ==================== 显示起始位置 ==================== */

/**
 * @brief 设置显示起始位置（页寻址模式）
 * @param page 页地址 0~7（每页 8 像素高）
 * @param col  列地址 0~127
 */
void SSD1306_OLED::set_pos(uint8_t page, uint8_t col)
{
    write_cmd(0xB0u + (page & 0x07u));             // 页地址
    write_cmd(0x00u + (col & 0x0Fu));              // 列低 4 位
    write_cmd(0x10u + ((col >> 4u) & 0x0Fu));      // 列高 4 位
}

