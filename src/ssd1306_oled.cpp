const char* SSD1306_OLED::motion_label(_filament_motion m)
{
    switch (m)
    {
        case _filament_motion::idle:             return "IDLE";
        case _filament_motion::send_out:         return "LOAD";
        case _filament_motion::before_on_use:    return "PREP";
        case _filament_motion::on_use:           return "FEED";
        case _filament_motion::stop_on_use:      return "STOP";
        case _filament_motion::before_pull_back: return "PRET";
        case _filament_motion::pull_back:        return "UNLD";
        default:                                 return "----";
    }
}

const char* SSD1306_OLED::material_label(uint8_t ch)
{
    if (ch >= 4) return "----";
    const _filament& f = ams[bambubus_local_ams_index()].filament[ch];

    /* TPU 材质：显示内部写死型号（如 GFU98/GFU90） */
    if (f.filament_type == _filament_type::tpu)
    {
        const char* id = TPU_FIXED_ID[ch];
        if (id && id[0]) return id;
        return "TPU?";
    }

    /* 非 TPU：优先用 Bambu 下发的 filament_id（如 GFG00/GFA00/GFB01） */
    if (f.bambubus_filament_id[0] && f.bambubus_filament_id[1])
    {
        const char* id = f.bambubus_filament_id;
        if (id[0] == 'G' && id[1] == 'F' && id[2] == 'G') return "PETG";
        if (id[0] == 'G' && id[1] == 'F' && id[2] == 'A') return "PLA";
        if (id[0] == 'G' && id[1] == 'F' && id[2] == 'B') return "ABS";
        if (id[0] == 'G' && id[1] == 'F' && id[2] == 'P') return "PC";
        if (id[0] == 'G' && id[1] == 'F' && id[2] == 'L') return "PA";
        if (id[0] == 'G' && id[1] == 'F' && id[2] == 'U') return "TPU";
        if (id[0] == 'A' && id[1] == 'B' && id[2] == 'S') return "ABS";

        /* id 未识别（第三方耗材）：改用名称关键词确认 */
        const char* m = material_from_name(f.name);
        if (m) return m;

        /* 无法识别：显示材质字母+两位序号（如 G00），保证有内容可看 */
        static char buf[8];
        buf[0] = id[2];
        buf[1] = id[3];
        buf[2] = id[4];
        buf[3] = 0;
        return buf;
    }

    if (f.name[0])
    {
        const char* m = material_from_name(f.name);
        if (m) return m;
        return f.name;
    }
    return "UNKN";
}

const char* SSD1306_OLED::color_name(uint8_t r, uint8_t g, uint8_t b)
{
    if (r < 30 && g < 30 && b < 30) return "BLACK";
    if (r > 225 && g > 225 && b > 225) return "WHITE";
    if (r >= g && r >= b)
    {
        if (g > 120 && b > 120) return "ORANGE";
        if (b > 120) return "PURPLE";
        if (g > 120) return "YELLOW";
        return "RED";
    }
    if (g >= r && g >= b)
    {
        if (r > 120 && b > 120) return "CYAN";
        if (b > 120) return "CYAN";
        if (r > 120) return "YELLOW";
        return "GREEN";
    }
    if (r > 120 && g > 120) return "CYAN";
    if (r > 120) return "PURPLE";
    if (g > 120) return "CYAN";
    return "BLUE";
}

void SSD1306_OLED::draw_channels()
{
    if (!s_ready) return;

    for (uint8_t r = 0; r < 4; r++)
    {
        char line[OLED_COLS + 1u];
        for (uint8_t i = 0; i < OLED_COLS; i++) line[i] = ' ';
        line[OLED_COLS] = 0;

        const _filament& f = ams[bambubus_local_ams_index()].filament[r];

        int n = 0;
        line[n++] = (char)('0' + r);
        line[n++] = ':';

        if (!f.online)
        {
            line[n++] = 'E'; line[n++] = 'M'; line[n++] = 'P'; line[n++] = 'T'; line[n++] = 'Y';
        }
        else if (fx_meters_le(f.meters, 0.05f))   /* 【定点化】纯位运算比较，不引入 __lesf2 */
        {
            line[n++] = 'N'; line[n++] = 'U'; line[n++] = 'L'; line[n++] = 'L';
            const char* c = color_name(f.color_R, f.color_G, f.color_B);
            for (int k = 0; c && c[k] && k < 7; k++) line[8 + k] = c[k];
        }
        else
        {
            const char* mat = material_label(r);
            int mi = 0;
            while (mat && mat[mi] && mi < 5) line[n++] = mat[mi++];
            while (n < 8) line[n++] = ' ';
            const char* c = color_name(f.color_R, f.color_G, f.color_B);
            for (int k = 0; c && c[k] && k < 7; k++) line[8 + k] = c[k];
        }

        draw_line_if_changed(r, line);
    }
}

/* ==================== 动作覆盖 + 页面轮询 ==================== */

void SSD1306_OLED::notify_action(uint8_t ch, oled_action act)
{
    if (!s_ready) return;
    if (ch >= 4) return;
    if (act == oled_action::action_none) return;
    s_action     = act;
    s_action_ch  = ch;
    s_action_until_ms = time_ms64() + OLED_ACTION_HOLD_MS;
    s_page_next_ms = 0;   // 立即打断轮询
}

void SSD1306_OLED::tick(bool aht20_present, bool aht20_online,
                        int16_t temperature_dc, uint16_t humidity_dc,
                        bool comm_ok)
{
    if (!s_ready)
    {
        /* 未检测到屏时，每 3 秒重探一次以支持中途插入 */
        static uint64_t s_last_probe_ms = 0;
        const uint64_t now = time_ms64();
        if (now - s_last_probe_ms < 3000u) return;
        s_last_probe_ms = now;
        if (!probe_ack()) return;
        s_ready = true;
        i2c2_init();
        delay(200);
        for (uint8_t i = 0; i < sizeof(InitCmd); i++)
            write_cmd(InitCmd[i]);
        clear();
        return;
    }

    const uint64_t now = time_ms64();

    /* ===== 1) 动作覆盖优先 ===== */
    if (s_action != oled_action::action_none && now < s_action_until_ms)
    {
        char l0[OLED_COLS + 1u];
        const char* actxt = "NONE";
        switch (s_action)
        {
            case oled_action::action_load:   actxt = "LOADING";  break;
            case oled_action::action_unload: actxt = "UNLOAD";   break;
            case oled_action::action_feed:   actxt = "FEEDING";  break;
            case oled_action::action_idle:   actxt = "STOP";     break;
            default:                         actxt = "NONE";     break;
        }
        int k = 0;
        l0[k++] = 'C'; l0[k++] = 'H'; l0[k++] = (char)('0' + s_action_ch); l0[k++] = ' ';
        for (int i = 0; actxt[i] && k < 16; i++) l0[k++] = actxt[i];
        while (k < 16) l0[k++] = ' ';
        l0[16] = 0;
        draw_line_if_changed(0, l0);
        draw_line_if_changed(1, material_label(s_action_ch));

        const char* hint = "";
        switch (s_action)
        {
            case oled_action::action_load:   hint = "feed in";   break;
            case oled_action::action_unload: hint = "pull out";  break;
            case oled_action::action_feed:   hint = "supplying"; break;
            default:                         hint = "";          break;
        }
        draw_line_if_changed(2, hint);
        draw_line_if_changed(3, "");
        return;
    }

    /* 动作结束：清动作状态，回轮询 */
    if (s_action != oled_action::action_none)
    {
        s_action = oled_action::action_none;
        s_action_ch = 0xFFu;
        clear();
    }

    /* ===== 2) 页面轮询 ===== */
    if (s_page_next_ms == 0u)
    {
        s_page_next_ms = now + OLED_PAGE_DWELL_MS;
    }
    else if (now >= s_page_next_ms)
    {
        s_page = (oled_page)((uint8_t)s_page + 1u);
        if (s_page >= oled_page::page_count) s_page = oled_page::page_aht20;
        s_page_next_ms = now + OLED_PAGE_DWELL_MS;
        clear();
    }

    switch (s_page)
    {
        case oled_page::page_aht20:
            draw_aht20(aht20_present, aht20_online, temperature_dc, humidity_dc, comm_ok);
            break;
        case oled_page::page_channels:
            draw_channels();
            break;
        default:
            break;
    }
}

