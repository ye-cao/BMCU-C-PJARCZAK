/**
 * @file ssd1306_oled.cpp
 * @brief SSD1306 OLED 驱动实现（硬件 I2C2）
 *
 * SSD1306 128x64 OLED 驱动，通过硬件 I2C2（PB10/PB11）通信。
 * 与 AHT20/SHT45 温湿度传感器共用同一条 I2C 总线，地址不同不冲突：
 *   AHT20 = 0x38, SHT45 = 0x44, SSD1306 = 0x3C
 *
 * 与 DZRAB 版本的区别：
 *   DZRAB 使用软件 I2C（g_aht20.bus_start/bus_write/bus_stop）
 *   本版本使用硬件 I2C2（i2c2_write()），速度更快、CPU 占用更低
 *
 * 字模移植自江协科技 OLED 库（STM32 参考），仅作字模数据来源。
 * 实际硬件为 BMCU 主板 CH32V203。
 */

